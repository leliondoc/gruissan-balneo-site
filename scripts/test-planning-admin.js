const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const phpTest = path.join(__dirname, 'test-planning-admin.php');
process.stdout.write(execFileSync('php', [phpTest], { encoding: 'utf8' }));
const fixtures = JSON.parse(execFileSync('php', [phpTest, '--fixtures'], { encoding: 'utf8' }));
const dom = new JSDOM(fixtures.form, { url: 'https://example.test/wp-admin/admin.php?page=balneo-planning&edit=parc', runScripts: 'outside-only' });
const { window } = dom;
const { document } = window;
window.eval(fs.readFileSync(path.join(root, 'wordpress-admin/js/schedule-admin.js'), 'utf8'));
const rules = document.querySelector('[data-planning-rules]');
const add = document.querySelector('[data-rule-add]');
assert.equal(rules.children.length, 1);
assert.equal(document.querySelector('[data-rule-period]').hidden, false);
assert.equal(document.querySelector('[data-rule-exception]').hidden, true);
add.click();
assert.equal(rules.children.length, 2);
const last = rules.lastElementChild;
const kind = last.querySelector('select[name$="[kind]"]');
kind.value = 'exception';
kind.dispatchEvent(new window.Event('change', { bubbles: true }));
assert.equal(last.querySelector('[data-rule-period]').hidden, true);
assert.equal(last.querySelector('[data-rule-exception]').hidden, false);
assert.equal(document.activeElement, kind);
const ids = [...document.querySelectorAll('[id]')].map((node) => node.id);
assert.equal(new Set(ids).size, ids.length, 'Les champs ont des identifiants uniques');
last.querySelector('[data-rule-up]').click();
assert.equal(rules.firstElementChild, last);
const formData = new window.FormData(document.querySelector('form'));
const kinds = [...formData.entries()].filter(([name]) => name.endsWith('[kind]'));
assert.equal(kinds[0][1], 'exception', 'La soumission suit le nouvel ordre du formulaire');
last.querySelector('[data-rule-remove]').click();
assert.equal(rules.children.length, 1);
for (let i = 0; i < 19; i++) add.click();
assert.equal(rules.children.length, 20);
assert.equal(add.disabled, true);
assert.equal(new window.FormData(document.querySelector('form')).get('form_complete'), '1');
dom.window.close();

const publicDom = new JSDOM(fixtures.public, { url: 'https://example.test/horaires/', runScripts: 'outside-only' });
const NativeDate = publicDom.window.Date;
publicDom.window.Date = class extends NativeDate { constructor(...args) { super(...(args.length ? args : ['2026-09-04T12:00:00Z'])); } };
publicDom.window.eval(fs.readFileSync(path.join(root, 'js/horaires.js'), 'utf8'));
let card = [...publicDom.window.document.querySelectorAll('.schedule-card')].find((node) => node.querySelector('h3').textContent === 'Aquagym du matin');
assert.ok(card, 'L’activité enregistrée en PHP est présente dans le calendrier');
assert.equal(card.hidden, false);
assert.equal(card.querySelector('.schedule-card__time').textContent, '09h30–10h15');
publicDom.window.document.querySelector('[data-date="2026-09-05"]').click();
assert.equal(card.hidden, true, 'Aucune séance le samedi');
publicDom.window.document.querySelector('[data-date="2026-09-11"]').click();
assert.equal(card.hidden, false);
assert.equal(card.querySelector('.schedule-card__time').textContent, 'Annulé');
assert.ok(card.classList.contains('is-closed'));
publicDom.window.close();
assert.match(fixtures.list, /Planning \/ Horaires/);
assert.match(fixtures.list, /Ajouter une activité/);
assert.equal(fs.readFileSync(path.join(root, 'wordpress-theme/balneo-v2/js/schedule-admin.js'), 'utf8'), fs.readFileSync(path.join(root, 'wordpress-admin/js/schedule-admin.js'), 'utf8'));
process.stdout.write('Planning admin validé : rendu PHP, formulaires, ajout/retrait/ordre des règles et liaison au calendrier public.\n');
